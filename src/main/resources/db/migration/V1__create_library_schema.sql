CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    CONSTRAINT uk_books_title_author UNIQUE (title, author)
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    cpf VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT uk_customers_cpf UNIQUE (cpf)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    cpf VARCHAR(255) NOT NULL,
    registration_number INTEGER NOT NULL,
    position VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT uk_employees_cpf UNIQUE (cpf),
    CONSTRAINT uk_employees_registration_number UNIQUE (registration_number)
);

CREATE TABLE customers_purchases (
    customer_id BIGINT NOT NULL,
    purchases_id BIGINT NOT NULL,
    CONSTRAINT uk_customers_purchases_book UNIQUE (purchases_id),
    CONSTRAINT fk_customers_purchases_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_customers_purchases_book
        FOREIGN KEY (purchases_id) REFERENCES books (id)
);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date DATE NOT NULL,
    book_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    CONSTRAINT fk_sales_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_sales_employee FOREIGN KEY (employee_id) REFERENCES employees (id)
);
